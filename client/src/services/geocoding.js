/**
 * Smart Geocoder: Resolves an address, locality, or PIN code into precise GPS coordinates.
 */
export function geocodeAddress({ address = '', city = '', pincode = '', state = '' }) {
  const queryStr = `${address} ${city} ${pincode} ${state}`.toLowerCase();

  // 1. Check exact pincode match first
  const cleanPin = (pincode || '').replace(/\D/g, '');
  if (cleanPin && INDIAN_LOCALITY_COORDINATES[cleanPin]) {
    const match = INDIAN_LOCALITY_COORDINATES[cleanPin];
    return {
      latitude: match.lat,
      longitude: match.lng,
      matchedBy: `Pincode: ${cleanPin} (${match.locality})`,
      accuracy: 'HIGH_PINCODE'
    };
  }

  // 2. Check locality substring match
  for (const [key, coords] of Object.entries(INDIAN_LOCALITY_COORDINATES)) {
    if (queryStr.includes(key)) {
      return {
        latitude: coords.lat,
        longitude: coords.lng,
        matchedBy: `Locality: ${coords.locality}`,
        accuracy: 'HIGH_LOCALITY'
      };
    }
  }

  // 3. Check city default match
  const cleanCity = city.trim().toLowerCase();
  for (const [cityKey, coords] of Object.entries(CITY_DEFAULT_COORDINATES)) {
    if (cleanCity.includes(cityKey) || queryStr.includes(cityKey)) {
      return {
        latitude: coords.lat,
        longitude: coords.lng,
        matchedBy: `City Center: ${coords.name}`,
        accuracy: 'CITY_LEVEL'
      };
    }
  }

  // Fallback to Bengaluru Central
  return {
    latitude: 12.9716,
    longitude: 77.5946,
    matchedBy: 'Default Metropolitan Center (Bengaluru)',
    accuracy: 'FALLBACK'
  };
}

/**
 * Browser GPS Geolocation Helper
 */
export function getBrowserGeolocation() {
  return new Promise((resolve, reject) => {
    if (!navigator.geolocation) {
      reject(new Error('Geolocation is not supported by your browser.'));
      return;
    }

    navigator.geolocation.getCurrentPosition(
      (pos) => {
        resolve({
          latitude: Number(pos.coords.latitude.toFixed(6)),
          longitude: Number(pos.coords.longitude.toFixed(6)),
          accuracyMeters: pos.coords.accuracy
        });
      },
      (err) => {
        reject(new Error(err.message || 'Unable to retrieve your location.'));
      },
      {
        enableHighAccuracy: true,
        timeout: 10000,
        maximumAge: 0
      }
    );
  });
}
